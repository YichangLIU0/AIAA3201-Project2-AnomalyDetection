from pathlib import Path
import sys,json,zipfile,shutil,subprocess
r=Path(__file__).resolve().parents[1];sys.path.insert(0,str(r/'coursework'))
import numpy as np
from common import CATEGORIES,OUT,DATA
from demo import Detector,panel
folder=r/'deliverables/demo';folder.mkdir(parents=True,exist_ok=True)
d=Detector();records=[]
for c in CATEGORIES:
 base=OUT/'dinov2'/c/'8shot_seed0_random25'
 with np.load(base/'predictions.npz') as saved:
  y=saved['masks'].reshape(len(saved['scores']),-1).any(1)
  for kind,idx in [('normal',int(np.flatnonzero(~y)[0])),('anomalous',int(np.flatnonzero(y)[0]))]:
   im,am,result=d.infer(DATA/str(saved['paths'][idx]),c)
   assert abs(result['score']-float(saved['scores'][idx]))<1e-5,(c,result['score'],saved['scores'][idx])
   assert np.allclose(am,saved['maps'][idx],atol=1e-5)
   result['ground_truth']=kind;result['matches_saved_prediction']=True
   panel(im,am,result).save(folder/f'frame_{len(records):02d}.png');records.append(result)
(folder/'predictions.json').write_text(json.dumps(records,indent=2))
(folder/'README.txt').write_text('Actual inference demonstration: first normal and first anomalous test image by filename for each of six categories. Ground truth is recorded separately in predictions.json. Decisions are actual model outputs, including mistakes. Each frame was regenerated by the runnable detector and checked against the evaluated predictions. Video holds each frame for 4 seconds. See the main code README for running the GUI. No camera hardware is required.\n')
ffmpeg=Path('C:/Program Files/ffmpeg-2025-11-06-git-222127418b-essentials_build/bin/ffmpeg.exe')
subprocess.run([str(ffmpeg),'-y','-framerate','1/4','-i',str(folder/'frame_%02d.png'),'-c:v','libx264','-r','25','-pix_fmt','yuv420p',str(folder/'anomaly_demo.mp4')],check=True,stdout=subprocess.DEVNULL,stderr=subprocess.PIPE)
with zipfile.ZipFile(r/'deliverables/anomaly_demo.zip','w',zipfile.ZIP_DEFLATED) as z:
 for p in folder.iterdir():z.write(p,p.name)
print('DEMO_COMPLETE',len(records),flush=True)
